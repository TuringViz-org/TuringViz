import type {
  ElkEdgeSection,
  ElkExtendedEdge,
  ElkNode,
  LayoutOptions,
} from '@openedges/elk-layout';

export type CompactElkGraph = {
  graph: ElkNode;
  restore: (result: ElkNode) => ElkNode;
};

// These options contain values, not graph element references. Unknown options
// and richer ELK graphs take the unchanged path instead of risking broken IDs.
const scalarOptions = new Set([
  'algorithm',
  'direction',
  'spacing.nodeNode',
  'layered.spacing.nodeNodeBetweenLayers',
  'spacing.edgeEdge',
  'spacing.edgeNode',
  'padding',
  'layered.nodePlacement.bk.fixedAlignment',
]);
const nodeKeys = new Set(['id', 'x', 'y', 'width', 'height', 'layoutOptions']);
const rootKeys = new Set([...nodeKeys, 'children', 'edges']);
const edgeKeys = new Set(['id', 'sources', 'targets', 'container']);

function safeOptions(options?: LayoutOptions): boolean {
  return Object.keys(options ?? {}).every((key) =>
    scalarOptions.has(key.replace(/^(?:org\.eclipse\.)?elk\./, ''))
  );
}

function hasOnlyKeys(value: object, allowed: Set<string>): boolean {
  return Object.keys(value).every((key) => allowed.has(key));
}

function copyOptions<T extends { layoutOptions?: LayoutOptions }>(value: T): T {
  return value.layoutOptions
    ? { ...value, layoutOptions: { ...value.layoutOptions } }
    : { ...value };
}

/**
 * Keep long configuration IDs out of worker messages and WASM JSON. Only the
 * flat, unlabelled graphs produced by buildElkGraph are compacted. The lookup
 * maps retain the original strings by reference, without copying their content.
 */
export function compactElkGraph(input: ElkNode): CompactElkGraph {
  const unchanged = { graph: input, restore: (result: ElkNode) => result };
  const algorithm =
    input.layoutOptions?.['elk.algorithm'] ??
    input.layoutOptions?.['org.eclipse.elk.algorithm'];
  if (
    (algorithm &&
      algorithm !== 'layered' &&
      algorithm !== 'org.eclipse.elk.layered') ||
    !hasOnlyKeys(input, rootKeys) ||
    !safeOptions(input.layoutOptions)
  ) {
    return unchanged;
  }

  const originals = new Map<string, string>([['r', input.id]]);
  const nodeIds = new Map<string, string>();
  const seenIds = new Set([input.id]);
  const children = input.children ?? [];
  const edges = input.edges ?? [];

  for (let index = 0; index < children.length; index++) {
    const node = children[index];
    if (
      !hasOnlyKeys(node, nodeKeys) ||
      !safeOptions(node.layoutOptions) ||
      seenIds.has(node.id)
    ) {
      return unchanged;
    }
    seenIds.add(node.id);
    const compactId = `n${index}`;
    nodeIds.set(node.id, compactId);
    originals.set(compactId, node.id);
  }

  for (let index = 0; index < edges.length; index++) {
    const edge = edges[index];
    if (
      !hasOnlyKeys(edge, edgeKeys) ||
      seenIds.has(edge.id) ||
      !edge.sources.every((id) => nodeIds.has(id)) ||
      !edge.targets.every((id) => nodeIds.has(id)) ||
      (edge.container !== undefined && edge.container !== input.id)
    ) {
      return unchanged;
    }
    seenIds.add(edge.id);
    originals.set(`e${index}`, edge.id);
  }

  const graph: ElkNode = {
    ...copyOptions(input),
    id: 'r',
    ...(input.children && {
      children: children.map((node, index) => ({
        ...copyOptions(node),
        id: `n${index}`,
      })),
    }),
    ...(input.edges && {
      edges: edges.map((edge, index) => ({
        ...edge,
        id: `e${index}`,
        sources: edge.sources.map((id) => nodeIds.get(id)!),
        targets: edge.targets.map((id) => nodeIds.get(id)!),
        ...(edge.container !== undefined && { container: 'r' }),
      })),
    }),
  };

  const originalId = (id: string): string => originals.get(id) ?? id;

  function restore(result: ElkNode): ElkNode {
    // Section IDs are generated by ELK from the edge ID. Build the whole lookup
    // first because a section can refer to another section appearing later.
    const sectionIds = new Map<string, string>();
    for (const edge of result.edges ?? []) {
      edge.sections?.forEach((section, index) => {
        sectionIds.set(section.id, `${originalId(edge.id)}_s${index}`);
      });
    }
    const sectionId = (id: string): string => sectionIds.get(id) ?? id;
    const restoreSection = (section: ElkEdgeSection): ElkEdgeSection => ({
      ...section,
      id: sectionId(section.id),
      ...(section.incomingShape !== undefined && {
        incomingShape: originalId(section.incomingShape),
      }),
      ...(section.outgoingShape !== undefined && {
        outgoingShape: originalId(section.outgoingShape),
      }),
      ...(section.incomingSections && {
        incomingSections: section.incomingSections.map(sectionId),
      }),
      ...(section.outgoingSections && {
        outgoingSections: section.outgoingSections.map(sectionId),
      }),
    });
    const restoreEdge = (edge: ElkExtendedEdge): ElkExtendedEdge => ({
      ...edge,
      id: originalId(edge.id),
      sources: edge.sources.map(originalId),
      targets: edge.targets.map(originalId),
      ...(edge.container !== undefined && {
        container: originalId(edge.container),
      }),
      ...(edge.sections && { sections: edge.sections.map(restoreSection) }),
    });
    return {
      ...result,
      id: originalId(result.id),
      ...(result.children && {
        children: result.children.map((node) => ({
          ...node,
          id: originalId(node.id),
        })),
      }),
      ...(result.edges && { edges: result.edges.map(restoreEdge) }),
    };
  }

  return { graph, restore };
}
